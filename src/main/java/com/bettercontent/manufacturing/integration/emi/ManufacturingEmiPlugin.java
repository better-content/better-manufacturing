package com.bettercontent.manufacturing.integration.emi;

import com.bettercontent.manufacturing.integration.create.DrillEngineering;
import com.bettercontent.manufacturing.persistence.BuildNbt;
import com.bettercontent.manufacturing.recipe.MaterialShapedRecipe;
import dev.emi.emi.api.*;
import dev.emi.emi.api.recipe.*;
import dev.emi.emi.api.stack.*;
import dev.emi.emi.api.widget.WidgetHolder;
import net.minecraft.core.RegistryAccess;
import net.minecraft.network.chat.Component;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.entity.player.Player;
import net.minecraft.world.inventory.*;
import net.minecraft.world.item.ItemStack;
import net.minecraftforge.registries.ForgeRegistries;
import slimeknights.tconstruct.library.materials.MaterialRegistry;
import slimeknights.tconstruct.library.tools.part.ToolPartItem;
import java.util.*;

/** Client-discovered optional EMI integration. Panels are generated by the actual crafting evaluator. */
@EmiEntrypoint
public final class ManufacturingEmiPlugin implements EmiPlugin {
    @Override public void register(EmiRegistry registry) {
        var nativeRecipe = registry.getRecipeManager().byKey(new ResourceLocation("create:crafting/kinetics/mechanical_drill")).orElse(null);
        if (!(nativeRecipe instanceof MaterialShapedRecipe recipe) || !MaterialRegistry.isFullyLoaded()) return;
        var item = ForgeRegistries.ITEMS.getValue(new ResourceLocation(DrillEngineering.CHASSIS));
        var part = ForgeRegistries.ITEMS.getValue(new ResourceLocation("tconstruct:pick_head"));
        if (item == null || !(part instanceof ToolPartItem headItem)) return;
        var category = new EmiRecipeCategory(new ResourceLocation("better_manufacturing:part_in_machine"), EmiStack.of(item));
        registry.addCategory(category); registry.addWorkstation(category, EmiStack.of(net.minecraft.world.item.Items.CRAFTING_TABLE));
        registry.setDefaultComparison(item, Comparison.compareData(stack -> stack.getNbt() == null ? null : stack.getNbt().get(BuildNbt.KEY)));
        var examples = new ArrayList<Panel>();
        for (var material : MaterialRegistry.getInstance().getVisibleMaterials()) {
            if (!headItem.canUseMaterial(material.getIdentifier())) continue;
            var head = headItem.withMaterial(material.getIdentifier());
            if (registry.isStackDisabled(EmiStack.of(head))) continue;
            var grid = grid();
            boolean complete = true;
            for (int i = 0; i < recipe.getIngredients().size(); i++) {
                var ingredient = recipe.getIngredients().get(i);
                int slot = i % recipe.getWidth() + (i / recipe.getWidth()) * 3;
                if (ingredient.isEmpty()) continue;
                var options = ingredient.getItems();
                if (options.length == 0) { complete = false; break; }
                grid.setItem(slot, options[0].copy());
            }
            if (!complete) continue;
            for (var transfer : recipe.transfers()) grid.setItem(transfer.slot() % recipe.getWidth() + transfer.slot() / recipe.getWidth() * 3, head.copy());
            ItemStack result = recipe.assemble(grid, RegistryAccess.EMPTY);
            if (result.isEmpty() || !DrillEngineering.evaluate(result.getTag()).allowed()) continue;
            var inputs = new ArrayList<EmiIngredient>();
            for (int i = 0; i < grid.getContainerSize(); i++) {
                int x = i % 3, y = i / 3;
                if (x >= recipe.getWidth() || y >= recipe.getHeight()) { inputs.add(EmiStack.EMPTY); continue; }
                int sourceSlot = x + y * recipe.getWidth();
                if (recipe.transfers().stream().anyMatch(t -> t.slot() == sourceSlot)) inputs.add(EmiStack.of(grid.getItem(i)));
                else inputs.add(EmiIngredient.of(recipe.getIngredients().get(sourceSlot)));
            }
            examples.add(new Panel(category, new ResourceLocation("better_manufacturing", "/drill/" + material.getIdentifier().getNamespace() + "/" + material.getIdentifier().getPath()),
                List.copyOf(inputs), EmiStack.of(result), DrillEngineering.evaluate(result.getTag()).rate(), recipe));
        }
        // The unbound vanilla preview would imply a stock result, losing the selected head in EMI.
        if (!examples.isEmpty()) {
            registry.removeRecipes(recipe.getId());
            registry.removeEmiStacks(stack -> stack.getKey().equals(item) && (stack.getNbt() == null || !stack.getNbt().contains(BuildNbt.KEY)));
            for (var panel : examples) { registry.addRecipe(panel); registry.addEmiStack(panel.output()); }
        }
        var retool = registry.getRecipeManager().byKey(new ResourceLocation("better_manufacturing:retool_drill_head")).orElse(null);
        var reference = examples.stream().filter(panel -> DrillEngineering.evaluate(panel.output().getNbt()).build().components().get("head").materialVariant().equals("tconstruct:iron")).findFirst();
        if (retool instanceof com.bettercontent.manufacturing.recipe.DrillRetoolingRecipe nativeRetool && reference.isPresent()) {
            var retoolCategory = new EmiRecipeCategory(new ResourceLocation("better_manufacturing:retooling"), EmiStack.of(net.minecraft.world.item.Items.CRAFTING_TABLE));
            registry.addCategory(retoolCategory); registry.addWorkstation(retoolCategory, EmiStack.of(net.minecraft.world.item.Items.CRAFTING_TABLE));
            for (var target : examples) {
                if (target == reference.get()) continue;
                var targetHead = com.bettercontent.manufacturing.tconstruct.NativeParts.recover(DrillEngineering.evaluate(target.output().getNbt()).build().components().get("head"));
                var input = grid(); input.setItem(0, reference.get().output().getItemStack().copy()); input.setItem(1, targetHead);
                var result = nativeRetool.assemble(input, RegistryAccess.EMPTY);
                var refund = nativeRetool.getRemainingItems(input).get(1);
                if (!result.isEmpty() && !refund.isEmpty()) registry.addRecipe(new RetoolPanel(retoolCategory,
                    new ResourceLocation("better_manufacturing", "/retool/" + target.id().getPath().substring(1)),
                    EmiStack.of(input.getItem(0)), EmiStack.of(targetHead).setRemainder(EmiStack.of(refund)), EmiStack.of(result), EmiStack.of(refund), nativeRetool));
            }
        }
    }
    private static CraftingContainer grid() {
        return new TransientCraftingContainer(new AbstractContainerMenu(null, 0) {
            @Override public ItemStack quickMoveStack(Player player, int slot) { return ItemStack.EMPTY; }
            @Override public boolean stillValid(Player player) { return true; }
        }, 3, 3);
    }
    private record RetoolPanel(EmiRecipeCategory category, ResourceLocation id, EmiStack machine, EmiStack replacement,
                               EmiStack output, EmiStack returnedHead, com.bettercontent.manufacturing.recipe.DrillRetoolingRecipe backing) implements EmiRecipe {
        @Override public EmiRecipeCategory getCategory() { return category; }
        @Override public ResourceLocation getId() { return id; }
        @Override public List<EmiIngredient> getInputs() { return List.of(machine, replacement); }
        @Override public List<EmiStack> getOutputs() { return List.of(output); }
        @Override public int getDisplayWidth() { return 176; }
        @Override public int getDisplayHeight() { return 80; }
        @Override public boolean supportsRecipeTree() { return false; }
        @Override public net.minecraft.world.item.crafting.Recipe<?> getBackingRecipe() { return backing; }
        @Override public void addWidgets(WidgetHolder widgets) {
            widgets.addSlot(machine, 0, 0); widgets.addSlot(replacement, 26, 0);
            widgets.addFillingArrow(54, 1, 60); widgets.addSlot(output, 88, 0).recipeContext(this);
            widgets.addSlot(returnedHead, 132, 0).appendTooltip(Component.translatable("better_manufacturing.emi.refund"));
            widgets.addText(Component.translatable("better_manufacturing.emi.refund"), 0, 28, 0x404040, false);
            widgets.addText(Component.translatable("better_manufacturing.emi.grid"), 0, 42, 0x404040, false);
            String rate = String.format(Locale.ROOT, "%.2f", DrillEngineering.evaluate(output.getNbt()).rate());
            widgets.addText(Component.translatable("better_manufacturing.emi.cutting", rate), 0, 56, 0x404040, false);
        }
    }
    private record Panel(EmiRecipeCategory category, ResourceLocation id, List<EmiIngredient> slots, EmiStack output,
                         double rate, MaterialShapedRecipe backing) implements EmiRecipe {
        @Override public EmiRecipeCategory getCategory() { return category; }
        @Override public ResourceLocation getId() { return id; }
        @Override public List<EmiIngredient> getInputs() { return slots.stream().filter(slot -> !slot.isEmpty()).toList(); }
        @Override public List<EmiStack> getOutputs() { return List.of(output); }
        @Override public int getDisplayWidth() { return 176; }
        @Override public int getDisplayHeight() { return 112; }
        @Override public boolean supportsRecipeTree() { return false; }
        @Override public net.minecraft.world.item.crafting.Recipe<?> getBackingRecipe() { return backing; }
        @Override public void addWidgets(WidgetHolder widgets) {
            for (int i = 0; i < slots.size(); i++) widgets.addSlot(slots.get(i), (i % 3) * 18, (i / 3) * 18);
            widgets.addFillingArrow(65, 18, 60);
            widgets.addSlot(output, 108, 13).large(true).recipeContext(this);
            String value = String.format(Locale.ROOT, "%.2f", rate);
            widgets.addText(Component.translatable("better_manufacturing.emi.cutting", value), 0, 62, 0x404040, false);
            widgets.addText(Component.translatable("better_manufacturing.emi.stress", value), 0, 74, 0x404040, false);
            widgets.addText(Component.translatable("better_manufacturing.emi.tier"), 0, 86, 0x404040, false);
            widgets.addText(Component.translatable("better_manufacturing.emi.retool"), 0, 98, 0x404040, false);
        }
    }
}
